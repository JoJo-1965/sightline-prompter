import assert from "node:assert/strict";
import { parsePointingCue, POINT_DIRECTIONS, pointingCueFiles } from "../src/client/pointing-cues.js";
import { editPack } from "../src/client/edit-pack.js";
import { createTakeLog } from "../src/client/take-log.js";

for ( const direction of POINT_DIRECTIONS ) assert.equal( parsePointingCue( `[point ${ direction }: chart]` ).direction, direction );
assert.equal( parsePointingCue( "[POINT upper left: Growth chart]" ).direction, "up-left" );
assert.equal( parsePointingCue( "[point down right]" ).graphic, null );
assert.equal( parsePointingCue( "[point left: \"Revenue, 2026\"]" ).graphic, "Revenue, 2026" );
assert.equal( parsePointingCue( "[point center: demo]" ).direction, "centre" );
for ( const text of [ "[smile]", "[point]", "[Say: \"point left\"]", "[point east: chart]", "{point: left}", "[point left: {record: on}]" ] ) assert.equal( parsePointingCue( text ), null, text );

const cue = { ...parsePointingCue( "[point left: growth-chart]" ), id: "point-001", section: 1, anchor: { afterWordIndex: null, beforeWordIndex: 4 }, contextBefore: "", contextAfter: "Here are the numbers." };
const snapshot = { id: "script-a", pointingCues: [ cue, { ...cue, id: "point-002", section: 2, graphic: "next-section" } ] };
const take = { section: 1, take: 1, title: "Opening", scriptSnapshotId: "script-a", start: 5, end: 10, status: "complete", markers: [], words: [ { i: 4, w: "Here", t: 6 }, { i: 5, w: "are", t: 6.4 } ], sentences: [ { from: 4, to: 5, s: 1, text: "Here are" } ] };
const data = { takes: [ { ...take, status: "retake" }, { ...take, take: 2, rating: "keeper", start: 12, end: 19, words: [ { i: 4, w: "Here", t: 13 } ] } ], scriptSnapshots: [ snapshot ] };
const original = JSON.stringify( data );
let manifest = JSON.parse( pointingCueFiles( data )["production-cues.json"] );
assert.equal( manifest.directionBasis, "presenter" );
assert.equal( manifest.scriptCues.length, 2, "Unrecorded section's cue remains authored intent" );
assert.equal( manifest.occurrences.length, 2, "Each actual take receives only its own section's cue" );
assert.equal( manifest.occurrences[0].selectedTake, false );
assert.equal( manifest.occurrences[1].selectedTake, true );
assert.equal( manifest.occurrences[1].sessionSeconds, 13 );
assert.equal( manifest.occurrences[1].timingSource, "live-voice-following" );
assert.equal( manifest.occurrences[0].gestureVerified, false );
assert.equal( JSON.stringify( data ), original, "An export cannot mutate the log" );

const reviewed = { ...data, postRecord: { takes: [ { section: 1, take: 2, status: "review", words: [ { scriptIndex: 4, start: 12.2, end: 12.5 } ] } ] } };
manifest = JSON.parse( pointingCueFiles( reviewed )["production-cues.json"] );
assert.equal( manifest.occurrences[1].sessionSeconds, 12.2 );
assert.equal( manifest.occurrences[1].timingSource, "post-record-transcription" );
assert.equal( manifest.occurrences[1].reviewRequired, true );
const uncertain = { ...reviewed, postRecord: { takes: [ { section: 1, take: 2, status: "uncertain", words: [ { scriptIndex: 4, start: 12.2, end: 12.5 } ] } ] } };
assert.equal( JSON.parse( pointingCueFiles( uncertain )["production-cues.json"] ).occurrences[1].sessionSeconds, null, "Uncertain review must not fall back to misleading live timing" );
const absent = { takes: [ { ...take, words: [] } ], scriptSnapshots: [ snapshot ] };
assert.equal( JSON.parse( pointingCueFiles( absent )["production-cues.json"] ).occurrences[0].timingSource, "unavailable" );
assert.equal( JSON.parse( pointingCueFiles( absent )["production-cues.json"] ).occurrences[0].sessionSeconds, null, "Unknown never becomes zero" );
const tail = { ...absent, takes: [ take ], scriptSnapshots: [ { ...snapshot, pointingCues: [ { ...cue, anchor: { afterWordIndex: 5, beforeWordIndex: null } } ] } ] };
assert.equal( JSON.parse( pointingCueFiles( tail )["production-cues.json"] ).occurrences[0].anchorUsed, "previous-spoken-word-end" );
const wrongScript = { ...absent, takes: [ { ...take, scriptSnapshotId: "script-b" } ] };
assert.equal( JSON.parse( pointingCueFiles( wrongScript )["production-cues.json"] ).occurrences.length, 0 );
assert.deepEqual( pointingCueFiles( { takes: [] } ), {}, "Older packs gain no invented cues" );
const formula = { ...absent, scriptSnapshots: [ { ...snapshot, pointingCues: [ { ...cue, graphic: "=1+1" } ] } ] };
assert.ok( pointingCueFiles( formula )["production-cues.csv"].includes( "'=1+1" ), "CSV references remain text" );
assert.ok( editPack( data )["PRODUCTION-CUES.md"].includes( "presenter's own left/right" ) );
let time = 100000;
const log = createTakeLog( { clock: () => time, snapshot: () => snapshot } );
log.tick( { active: true, index: 0, advanced: true } );
time += 2500;
log.tick( { active: true, index: 0, advanced: true } );
log.tick( { active: false, index: 0, atEnd: true } );
assert.equal( log.data().scriptSnapshots[0].pointingCues[0].graphic, "growth-chart" );
assert.equal( JSON.parse( editPack( log.data() )["production-cues.json"] ).occurrences[0].directionBasis, "presenter" );
console.log( "Pointing cues: eight directions/centre, presenter basis, optional/quoted asset labels, per-snapshot/take picks, reviewed/live/unavailable anchors and backwards-compatible exports pass" );
