import assert from "node:assert/strict";
import { APPEARANCE_DEFAULTS, captureReadingTheme, normaliseReadingTheme, normaliseReadingThemes, settingsFromTheme, upgradeReadingAppearance } from "../src/client/reading-appearance.js";
import { createSettingsDraft } from "../src/client/settings-draft.js";
import { INTERFACE_DEFAULTS, upgradeInterfaceSettings, settingsSectionAvailable, voiceInputEnabled, customInputEnabled } from "../src/client/interface-state.js";
import { helpTabs, voiceHelpTabs } from "../src/client/help-tabs.js";
import { controlView } from "../src/client/control-actions.js";
import { readReadingTheme, writeReadingTheme } from "../src/reading-theme-files.js";
import fs from "node:fs/promises";
import os from "node:os";
import path from "node:path";

const source = { ...APPEARANCE_DEFAULTS, theme: "cream", headingScale: 1.2, directionScale: 0.8, productionNoteScale: 1.4, directions: "normal", scriptFont: "verdana", headingFont: "atkinson", directionFont: "opendyslexic", productionNoteFont: "same", scriptItalic: true, productionNoteBold: true, scriptColour: "#112233", backgroundColour: "#ffeedd", obsEnabled: true, deepgramApiKey: "private-never-export", remoteToken: "private-never-export", padLayout: { buttons: [ "marker" ] } };
const theme = captureReadingTheme( "Studio", source, { fontSize: 3.25, opacity: 0.62 } );
const spaced = captureReadingTheme( "Paragraphs", { ...source, paragraphSpacing: 0.45 }, { fontSize: 3.25, opacity: 0.62 } );
assert.equal( spaced.text.script.paragraphSpacing, 45, "Paragraph gaps are independent of line spacing" );
assert.equal( settingsFromTheme( spaced ).settings.paragraphSpacing, 0.45 );
const oldTheme = structuredClone( spaced ); delete oldTheme.text.script.paragraphSpacing;
assert.equal( settingsFromTheme( oldTheme ).settings.paragraphSpacing, 1, "Older themes retain the established paragraph gaps" );
assert.throws( () => normaliseReadingTheme( { ...spaced, text: { ...spaced.text, script: { ...spaced.text.script, paragraphSpacing: -1 } } } ), /paragraph/i );
assert.equal( theme.text.script.size, 325 );
assert.equal( theme.text.headings.size, 180 );
assert.equal( theme.text.inline.size, 68 );
assert.equal( theme.text.production.size, 77 );
assert.equal( theme.background["background-colour"], "#ffeedd" );
assert.ok( !JSON.stringify( theme ).includes( "private-never-export" ) );
assert.ok( !JSON.stringify( theme ).includes( "obsEnabled" ) );
assert.ok( !JSON.stringify( theme ).includes( "padLayout" ) );
const restored = settingsFromTheme( theme );
for ( const key of [ "scriptFont", "headingFont", "directionFont", "productionNoteFont", "scriptItalic", "productionNoteBold", "scriptColour", "backgroundColour", "headingScale", "directionScale", "productionNoteScale", "directions" ] ) assert.equal( restored.settings[key], source[key], key );
assert.equal( restored.fontSize, 3.25 );
assert.equal( restored.opacity, 0.62 );
assert.equal( restored.settings.obsEnabled, undefined );
assert.equal( normaliseReadingTheme( { ...theme, deepgramApiKey: "private-never-export" } ).deepgramApiKey, undefined );
assert.throws( () => normaliseReadingTheme( { ...theme, background: { ...theme.background, "background-colour": "url(https://example.invalid)" } } ), /background colour/ );
assert.throws( () => normaliseReadingTheme( { ...theme, text: { ...theme.text, script: { ...theme.text.script, font: "Follow script" } } } ), /font/ );
assert.throws( () => normaliseReadingTheme( { ...theme, text: { ...theme.text, script: { ...theme.text.script, size: Infinity } } } ), /size/ );
assert.throws( () => normaliseReadingThemes( [ theme, theme ] ), /unique/ );
assert.throws( () => normaliseReadingThemes( Array( 51 ).fill( theme ) ), /50/ );
const legacy = upgradeReadingAppearance( { directions: "normal", directionScale: 1, headingFont: "verdana", theme: "cream" } );
assert.equal( legacy.directionScale * 0.85, 1 );
assert.equal( legacy.directionFont, "verdana" );
assert.equal( legacy.backgroundColour, "#000000" );
assert.deepEqual( upgradeReadingAppearance( legacy ), legacy );

const draft = createSettingsDraft( { colour: "white", obsEnabled: false, themes: [] } );
draft.stage( { colour: "mint", obsEnabled: true } );
assert.equal( draft.dirty, true );
draft.rebase( { themes: [ { name: "New explicit preset" } ] } );
assert.equal( draft.value.colour, "mint" );
assert.equal( draft.value.themes.length, 1 );
const cancelled = draft.cancel();
assert.equal( cancelled.colour, "white" );
assert.equal( cancelled.obsEnabled, false );
assert.equal( cancelled.themes.length, 1 );
draft.stage( { obsEnabled: true } );
draft.commit();
draft.stage( { obsEnabled: false } );
assert.equal( draft.cancel().obsEnabled, true );
draft.stage( { themes: [ { name: "Edit" } ] } );
draft.value.themes[0].name = "must not mutate the transaction";
assert.equal( draft.value.themes[0].name, "Edit" );
console.log( "PASS: reading-theme isolation, round-trip, validation, legacy appearance and Settings Apply/Cancel/rebase" );
assert.equal( upgradeInterfaceSettings( { gamepadEnabled: false } ).gamepadEnabled, false );
assert.equal( upgradeInterfaceSettings( {} ).speechEnabled, true, "Migrate existing implicit opt-ins" );
assert.equal( upgradeInterfaceSettings( INTERFACE_DEFAULTS ).speechEnabled, false, "Fresh profiles keep explicit opt-ins off" );
assert.equal( settingsSectionAvailable( { obsEnabled: false }, "obs-recording" ), false );
assert.equal( settingsSectionAvailable( { obsEnabled: false }, "obs" ), true );
assert.equal( settingsSectionAvailable( { speechEnabled: false }, "words" ), false );
assert.equal( voiceInputEnabled( { speechEnabled: true, microphoneEnabled: false } ), false );
assert.equal( customInputEnabled( { keyboardMappingsEnabled: false }, "key" ), false );
assert.deepEqual( voiceHelpTabs( { speechEnabled: false, voiceCommands: "always" } ), [] );
const off = { ...INTERFACE_DEFAULTS, voiceCommands: "always", obsEnabled: false, streamDeck: false };
assert.equal( helpTabs( off ).some( tab => tab.label === "Voice" ), false );
assert.equal( controlView( "sound-check", off ).hidden, true );
assert.equal( controlView( "pad", off ).hidden, true );
assert.equal( controlView( "listening-toggle", off ).hidden, true );
assert.equal( controlView( "head-guide", off ).hidden, false, "A hidden guide retains its show action" );
const temporary = await fs.mkdtemp( path.join( os.tmpdir(), "sightline-theme-files-" ) );
try {
	const file = path.join( temporary, "studio.json" );
	await writeReadingTheme( file, { ...theme, credentials: "must-not-export" } );
	assert.equal( ( await readReadingTheme( file ) ).name, theme.name );
	assert.equal( ( await fs.readFile( file, "utf8" ) ).includes( "must-not-export" ), false );
	await fs.writeFile( file, "{not json}" );
	await assert.rejects( readReadingTheme( file ), /valid reading-theme JSON/ );
	await fs.writeFile( file, " ".repeat( 100001 ) );
	await assert.rejects( readReadingTheme( file ), /100 KB/ );
} finally {
	assert.ok( path.resolve( temporary ).startsWith( path.resolve( os.tmpdir() ) + path.sep ) && path.basename( temporary ).startsWith( "sightline-theme-files-" ) );
	await fs.rm( temporary, { recursive: true, force: true } );
}
console.log( "PASS: optional-interface migration/gates, conditional help/actions and bounded credential-free theme files" );
