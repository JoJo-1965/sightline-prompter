import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";
import os from "node:os";
import { spawnSync, execFileSync } from "node:child_process";
import { fileURLToPath } from "node:url";
const root = path.resolve( path.dirname( fileURLToPath( import.meta.url ) ), ".." );
const fixture = fs.mkdtempSync( path.join( os.tmpdir(), "sightline-grid-check-" ) );
const write = ( file, value ) => {
	const target = path.resolve( fixture, file );
	assert.ok( target.startsWith( `${ fixture }${ path.sep }` ) );
	fs.mkdirSync( path.dirname( target ), { recursive: true } );
	fs.writeFileSync( target, value );
};
for ( const file of [ "scripts/build-feature-grid.mjs", "scripts/check-docs-sync.mjs" ] ) write( file, fs.readFileSync( path.join( root, file ) ) );
const original = "# Fixture grid\n\n**Review basis: Fixture Preview, documentation revision 1, 1 January 2026.**\n**Build version:** `1.0.0` · **Publication status:** Preview\n\n**Maintained source:** [Grid](https://github.com/example/app/blob/codex/fixture/docs/FEATURE-GRID.md)\n\nBuilt from `abc1234`, with companion Stream Deck plugin **1.0.0**. The public app release remains **1.0.0**.\n\n## 01 · Prompting\n\nReference: [Guide](guide/test.md).\n\n| Capability | Availability | Options and behaviour | Dependencies and limits |\n| --- | --- | --- | --- |\n| Read | Included | A script | A screen |\n";
write( "docs/FEATURE-GRID.md", original );
write( "package.json", JSON.stringify( { version: "1.0.0", type: "module" } ) );
for ( const match of original.matchAll( /\]\(([^)#]+)(?:#[^)]*)?\)/g ) ) {
	if ( /^https?:/.test( match[1] ) || /^FEATURE-GRID\./.test( match[1] ) ) continue;
	write( `docs/${ match[1] }`, "Fixture reference\n" );
}
const run = ( script, ...args ) => spawnSync( process.execPath, [ path.join( fixture, "scripts", script ), ...args ], { cwd: fixture, encoding: "utf8", env: { ...process.env, GITHUB_REF_NAME: "" } } );
const build = ( ...args ) => run( "build-feature-grid.mjs", ...args );
assert.equal( build().status, 0 );
assert.equal( build( "--check" ).status, 0 );
fs.appendFileSync( path.join( fixture, "docs/FEATURE-GRID.csv" ), "stale" );
assert.equal( build( "--check" ).status, 1, "Stale CSV is rejected" );
assert.equal( build().status, 0 );
fs.appendFileSync( path.join( fixture, "docs/FEATURE-GRID.html" ), "stale" );
assert.equal( build( "--check" ).status, 1, "Stale HTML is rejected" );
assert.equal( build().status, 0 );
assert.equal( build( "--check", "--release" ).status, 1, "Preview snapshot cannot accompany a stable release" );
write( "docs/FEATURE-GRID.md", original.replace( "**Build version:** `1.0.0`", "**Build version:** `9.9.9`" ) );
assert.match( build( "--check", "--release" ).stderr, /does not describe package/ );
write( "docs/FEATURE-GRID.md", original.replace( "Fixture Preview", "Sightline 1.0.0 release" ).replace( "**Publication status:** Preview", "**Publication status:** Released" ).replaceAll( "/blob/codex/fixture/", "/blob/v1.0.0/" ) );
assert.equal( build().status, 0 );
assert.equal( build( "--check", "--release" ).status, 0, "Matching released reference passes" );
execFileSync( "git", [ "init", "-q" ], { cwd: fixture } );
execFileSync( "git", [ "add", "." ], { cwd: fixture, stdio: "pipe" } );
fs.appendFileSync( path.join( fixture, "docs/FEATURE-GRID.html" ), "unstaged change" );
assert.equal( build( "--check", "--staged" ).status, 0, "Staged check reads the index, not unrelated work" );
fs.appendFileSync( path.join( fixture, "docs/FEATURE-GRID.md" ), "\nNew review note\n" );
execFileSync( "git", [ "add", "docs/FEATURE-GRID.md" ], { cwd: fixture } );
assert.equal( build( "--check", "--staged" ).status, 1, "Staged source with old exports fails" );
assert.equal( build().status, 0 );
const files = "src/client/teleprompter.js,readme.md,docs/FEATURES.md,ROADMAP.md";
assert.equal( run( "check-docs-sync.mjs", `--files=${ files }` ).status, 1, "User-facing change needs a matrix review" );
assert.equal( run( "check-docs-sync.mjs", `--files=${ files },docs/FEATURE-GRID-REVIEWS.md` ).status, 0, "Explicit no-feature-impact review is allowed" );
console.log( "Feature grid guards pass: stale exports, version/release labels, staged index and required capability review." );
