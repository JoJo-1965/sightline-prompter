import assert from "node:assert/strict";
import { createControlDispatcher } from "../src/control-dispatch.js";
import { guideValue } from "../src/client/guide-values.js";
let time = 0;
let number = 0;
const state = { obs: { enabled: true, controls: true, connection: "connected", recording: "recording", recordingId: "a" } };
const sent = [];
const controls = createControlDispatcher( { getStatus: () => state, onCommand: ( id, value ) => sent.push( { id, value } ), clock: () => time, token: () => `ticket-${ ++number }` } );
await assert.rejects( controls.command( "obs-finish" ), /Hold/ );
let ticket = controls.hold( "begin" );
time += 999;
await assert.rejects( controls.command( "obs-finish", { holdToken: ticket.token } ), /Hold/ );
time += 10;
await assert.rejects( controls.command( "obs-finish", { holdToken: ticket.token } ), /Hold/, "an early attempt consumes its ticket" );
ticket = controls.hold( "begin" );
controls.hold( "cancel", ticket.token );
time += 1100;
await assert.rejects( controls.command( "obs-finish", { holdToken: ticket.token } ), /Hold/ );
ticket = controls.hold( "begin" );
time += 1100;
await controls.command( "obs-finish", { holdToken: ticket.token } );
assert.equal( sent.length, 1 );
await assert.rejects( controls.command( "obs-finish", { holdToken: ticket.token } ), /Hold/, "tickets cannot be replayed" );
ticket = controls.hold( "begin" );
state.obs.recordingId = "b";
time += 1100;
await assert.rejects( controls.command( "obs-finish", { holdToken: ticket.token } ), /Hold/ );
ticket = controls.hold( "begin" );
state.obs.connection = "disconnected";
controls.observe();
state.obs.connection = "connected";
time += 1100;
await assert.rejects( controls.command( "obs-finish", { holdToken: ticket.token } ), /Hold/, "a transient disconnect invalidates the ticket" );
ticket = controls.hold( "begin" );
time += 6001;
await assert.rejects( controls.command( "obs-finish", { holdToken: ticket.token } ), /Hold/ );
state.padLayout = { holdToFinish: false };
await controls.command( "obs-finish" );
assert.equal( sent.length, 2 );
assert.deepEqual( guideValue( { axis: "background", value: 0 } ), { axis: "background", value: 0 } );
assert.deepEqual( guideValue( { axis: "top", value: 1.234 } ), { axis: "top", value: 1.23 } );
for ( const value of [ { axis: "x", value: 50 }, { axis: "x", value: "2" }, { axis: "top", value: NaN }, { axis: "x", value: 1, steps: 1 }, { axis: "bounds", value: 1 } ] ) assert.throws( () => guideValue( value ) );
console.log( "Pad/phone finish tickets: duration, cancellation, replay, changed recording, transient disconnect, expiry, opt-out and bounded sliders pass" );
