import assert from "node:assert/strict";
import fs from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import { createRecordingLink } from "../src/client/recording-link.js";
import { createStreamDeckDiscovery } from "../src/stream-deck-discovery.js";
import { matchCommand } from "../src/client/voice-commands.js";

const settings = { obsEnabled: true, obsControls: true, obsFollowPrompter: false };
const state = { enabled: true, controls: true, connection: "connected", recording: "stopped", recordingId: "one-file" };
const actions = [];
const link = createRecordingLink( { getSettings: () => settings, getState: () => state, command: async ( action ) => {
	actions.push( action );
	state.recording = { start: "recording", pause: "paused", resume: "recording", stop: "stopped" }[action];
	return true;
} } );
await link.start();
await link.pause();
await link.finish();
assert.deepEqual( actions, [], "Continuous mode must not control the recorder through ordinary playback" );
settings.obsFollowPrompter = true;
await Promise.all( [ link.start(), link.pause(), link.start(), link.finish() ] );
assert.deepEqual( actions, [ "start", "pause", "resume", "stop" ], "Start/pause/resume/finish are serialised" );
assert.equal( state.recordingId, "one-file", "Pause and resume do not create a new file identity" );
settings.obsEnabled = false;
await link.start();
await link.pause();
await link.finish();
assert.equal( actions.length, 4, "Disabled OBS cannot execute linked actions" );
settings.obsEnabled = true;
state.connection = "disconnected";
assert.equal( await link.start(), false, "Prompting waits when recording cannot be confirmed" );
for ( const [ words, id ] of [ [ [ "record", "on" ], "obs-on" ], [ [ "record", "off" ], "obs-off" ], [ [ "record", "pause" ], "obs-pause" ], [ [ "record", "resume" ], "obs-resume" ] ] ) assert.equal( matchCommand( words ), id );

const dir = await fs.mkdtemp( path.join( os.tmpdir(), "sightline-pairing-" ) );
const standardFile = path.join( dir, "standard.json" );
const localFile = path.join( dir, "preview", "local.json" );
await fs.writeFile( standardFile, "original-installed-descriptor" );
const discovery = createStreamDeckDiscovery( { standardFile, localFile } );
discovery.publish( { url: "http://127.0.0.1:12345", token: "test-only" } );
assert.equal( JSON.parse( await fs.readFile( standardFile ) ).profile, "Preview" );
discovery.release();
assert.equal( await fs.readFile( standardFile, "utf8" ), "original-installed-descriptor" );
discovery.publish( { url: "http://127.0.0.1:12345", token: "test-only" } );
await fs.writeFile( standardFile, "newer-app-pairing" );
discovery.release();
assert.equal( await fs.readFile( standardFile, "utf8" ), "newer-app-pairing", "Do not overwrite a newer app's pairing" );
const isolated = createStreamDeckDiscovery( { standardFile, localFile, claimCustom: false } );
isolated.publish( { token: "unused-test-token" } );
assert.equal( await fs.readFile( standardFile, "utf8" ), "newer-app-pairing", "Isolated test profiles do not claim the plugin" );
console.log( "Recording workflow: opt-in coupling, serialisation, disabled/disconnected guards, voice commands and reversible preview pairing pass" );
